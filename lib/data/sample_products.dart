const _img = 'assets/images/';

// Rounds a box price to the nearest 5 pesos so the sample prices look natural.
double _box(double single, int count, double discount) =>
    ((single * count * discount) / 5).round() * 5.0;

List<ProductVariation> _cookieVariations(double p) => [
  ProductVariation(label: 'Single cookie', price: p),
  ProductVariation(label: 'Box of 4', price: _box(p, 4, 0.95), units: 4),
  ProductVariation(label: 'Box of 6', price: _box(p, 6, 0.93), units: 6),
  ProductVariation(label: 'Box of 12', price: _box(p, 12, 0.9), units: 12),
];

